"""Generate the embedded Curiosity splash. Requires Pillow and numpy."""
import argparse
import json
from pathlib import Path

import numpy as np
from PIL import Image

BACKGROUND = (10, 12, 24)


def packbits(data):
    result = bytearray()
    i = 0
    while i < len(data):
        run = 1
        while i + run < len(data) and run < 128 and data[i + run] == data[i]:
            run += 1
        if run >= 3:
            result.extend((257 - run, data[i]))
            i += run
        else:
            start = i
            i += run
            while i < len(data) and i - start < 128:
                if i + 2 < len(data) and data[i] == data[i + 1] == data[i + 2]:
                    break
                i += 1
            result.append(i - start - 1)
            result.extend(data[start:i])
    return bytes(result)


def unpackbits(data):
    result = bytearray()
    i = 0
    while i < len(data):
        control = data[i]
        i += 1
        if control < 128:
            result.extend(data[i:i + control + 1])
            i += control + 1
        elif control > 128:
            result.extend([data[i]] * (257 - control))
            i += 1
    return bytes(result)


def cap_coverage():
    # Six-pixel capsule, 8x8 subpixel coverage for each of its left 3 columns.
    result = []
    for y in range(6):
        for x in range(3):
            inside = sum((x + (sx + .5) / 8 - 3) ** 2 +
                         (y + (sy + .5) / 8 - 3) ** 2 <= 9
                         for sx in range(8) for sy in range(8))
            result.append(round(inside * 15 / 64))
    return result


def bar_pixel(x, y, width, caps):
    if x >= width:
        return 0
    if x < 3:
        return caps[y * 3 + x]
    if x >= width - 3:
        return caps[y * 3 + width - 1 - x]
    return 15


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--header', type=Path, default=Path('device/sama7d65/splash_logo.h'))
    parser.add_argument('--output', type=Path, default=Path('build/curiosity_zephyr_splash'))
    args = parser.parse_args()
    rgb = np.asarray(Image.open(args.source).convert('RGB'))
    # Background is below 32 in every channel. Include all visible AA edges.
    bounds = Image.fromarray((rgb.max(2) > 32).astype('uint8') * 255).getbbox()
    if bounds is None:
        raise ValueError('No white artwork found')
    x0, y0, x1, y1 = bounds
    crop = (max(0, x0 - 1), max(0, y0 - 1), min(rgb.shape[1], x1 + 1), min(rgb.shape[0], y1 + 1))
    artwork = rgb[crop[1]:crop[3], crop[0]:crop[2]]
    logo_h, logo_w = artwork.shape[:2]
    width = (logo_w + 1) & ~1
    bar_y = logo_h + 24
    height = (bar_y + 6 + 1) & ~1
    if width < 320 or width > 1280 or height > 800:
        raise ValueError('Artwork does not fit the native splash layout')
    palette = np.array([[round(b + (255 - b) * i / 15) for b in BACKGROUND]
                        for i in range(16)], dtype='uint8')
    # Flatten the dark gradient to BASE color; keep the white logo's AA coverage.
    luma = artwork.astype(float).mean(2)
    coverage = np.clip((luma - 18) / (255 - 18), 0, 1)
    indices = np.zeros((height, width), dtype='uint8')
    indices[:logo_h, :logo_w] = np.rint(coverage * 15).astype('uint8')
    # DS60001851E Table 48.10: p0 is bits 3:0, p1 is bits 7:4.
    packed = (indices[:, 0::2] | (indices[:, 1::2] << 4)).tobytes()
    compressed = packbits(packed)
    assert unpackbits(compressed) == packed
    assert len(packed) <= 65536 and width % 2 == height % 2 == 0
    caps = cap_coverage()
    lines = ['/* Generated by scripts/make_splash.py; SPDX-License-Identifier: MIT */',
             '#ifndef SAMA7D65_SPLASH_LOGO_H', '#define SAMA7D65_SPLASH_LOGO_H',
             f'#define SPLASH_WIDTH {width}', f'#define SPLASH_HEIGHT {height}',
             f'#define SPLASH_BYTES {len(packed)}', f'#define SPLASH_BAR_Y {bar_y}',
             '#define SPLASH_BAR_WIDTH 320', '#define SPLASH_BAR_HEIGHT 6',
             f'#define SPLASH_BAR_X {(width - 320) // 2}',
             'static const unsigned int splash_palette[16] = {']
    lines.extend(f'\t0xff{r:02x}{g:02x}{b:02x},' for r, g, b in palette)
    lines.extend(['};', 'static const unsigned char splash_caps[18] = {',
                  '\t' + ', '.join(str(x) for x in caps), '};',
                  'static const unsigned char splash_rle[] = {'])
    lines.extend('\t' + ', '.join(f'0x{x:02x}' for x in compressed[i:i + 16]) + ','
                 for i in range(0, len(compressed), 16))
    lines.extend(['};', '#endif', ''])
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text('\n'.join(lines))
    args.output.mkdir(parents=True, exist_ok=True)
    origin = ((1280 - width) // 2, (800 - height) // 2)
    for progress in (0, 60, 100):
        preview = indices.copy()
        fill = 320 * progress // 100
        for y in range(6):
            for x in range(320):
                track = (3 * bar_pixel(x, y, 320, caps) + 7) // 15
                ink = bar_pixel(x, y, fill, caps) if fill >= 6 else 0
                preview[bar_y + y, (width - 320) // 2 + x] = max(track, ink)
        canvas = Image.fromarray(palette[preview])
        screen = Image.new('RGB', (1280, 800), BACKGROUND)
        screen.paste(canvas, origin)
        screen.save(args.output / f'splash-{progress}.png')
    Image.fromarray(palette[indices[:logo_h, :logo_w]]).save(args.output / 'logo-cropped.png')
    metrics = dict(source_size=[rgb.shape[1], rgb.shape[0]], crop_box=list(crop),
                   logo_size=[logo_w, logo_h], overlay_size=[width, height],
                   overlay_origin=list(origin), bar_origin=[origin[0] + (width - 320) // 2, origin[1] + bar_y],
                   framebuffer_bytes=len(packed), rle_bytes=len(compressed),
                   mode='4-bit indexed / 16 colors', palette_bytes=64)
    (args.output / 'splash-layout.json').write_text(json.dumps(metrics, indent=2) + '\n')
    print(json.dumps(metrics, indent=2))


if __name__ == '__main__':
    main()
